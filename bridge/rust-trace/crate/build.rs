#![forbid(unsafe_code)]
//! Fail-closed build script for `omega-trace`.
//! Invokes the pure seeded-Omega `om_lock_gen verify` binary and materializes the
//! verified byte-level SHA-256 chain from `OMEGA_TRACE.lock` into compile-time constants.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn resolve_work_dir(manifest_dir: &Path) -> PathBuf {
    if let Ok(p) = env::var("OMEGA_TRACE_WORK_DIR") {
        let pb = PathBuf::from(p);
        if pb.is_absolute() {
            return pb;
        }
        return manifest_dir.join(pb);
    }
    manifest_dir.join("../work")
}

fn resolve_file(env_key: &str, fallback: PathBuf) -> PathBuf {
    if let Ok(v) = env::var(env_key) {
        if !v.is_empty() {
            return PathBuf::from(v);
        }
    }
    fallback
}

fn req<'a>(map: &'a BTreeMap<String, String>, key: &str) -> &'a str {
    map.get(key)
        .unwrap_or_else(|| panic!("FAIL-CLOSED: OMEGA_TRACE.lock missing required key `{key}`"))
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let rust_trace_dir = manifest_dir
        .parent()
        .expect("crate must sit inside bridge/rust-trace/crate")
        .to_path_buf();
    let repo_root = rust_trace_dir
        .parent()
        .and_then(|p| p.parent())
        .map(Path::to_path_buf)
        .unwrap_or_else(|| rust_trace_dir.clone());

    let work_dir = resolve_work_dir(&manifest_dir);
    let verifier = resolve_file("OMEGA_TRACE_VERIFIER", work_dir.join("om_lock_gen"));
    let lock_file = resolve_file("OMEGA_TRACE_LOCK", work_dir.join("OMEGA_TRACE.lock"));
    let src_om = resolve_file("OMEGA_TRACE_SRC_OM", rust_trace_dir.join("sample_unit.om"));
    let omc_bin = resolve_file("OMEGA_OMC", repo_root.join("seed/out/omc"));
    let egp3_cert = resolve_file("OMEGA_TRACE_EGP3", work_dir.join("sample_unit.egp3"));
    let lean_src = resolve_file(
        "OMEGA_TRACE_LEAN",
        rust_trace_dir.join("proof/TraceBridge.lean"),
    );
    let ompk_pkg = resolve_file("OMEGA_TRACE_OMPK", work_dir.join("sample_unit.ompk"));
    let unit_bin = resolve_file("OMEGA_TRACE_UNIT_BIN", work_dir.join("sample_unit.bin"));
    let native_c = resolve_file(
        "OMEGA_TRACE_NATIVE_C",
        work_dir.join("omega_trace_native.c"),
    );
    let unit_obj = resolve_file(
        "OMEGA_TRACE_UNIT_OBJ",
        work_dir.join("omega_trace_native.o"),
    );

    for env_key in [
        "OMEGA_TRACE_WORK_DIR",
        "OMEGA_TRACE_VERIFIER",
        "OMEGA_TRACE_LOCK",
        "OMEGA_TRACE_SRC_OM",
        "OMEGA_OMC",
        "OMEGA_TRACE_EGP3",
        "OMEGA_TRACE_LEAN",
        "OMEGA_TRACE_OMPK",
        "OMEGA_TRACE_UNIT_BIN",
        "OMEGA_TRACE_NATIVE_C",
        "OMEGA_TRACE_UNIT_OBJ",
    ] {
        println!("cargo:rerun-if-env-changed={env_key}");
    }

    for dep in [
        &verifier, &lock_file, &src_om, &omc_bin, &egp3_cert, &lean_src, &ompk_pkg, &unit_bin,
        &native_c, &unit_obj,
    ] {
        println!("cargo:rerun-if-changed={}", dep.display());
    }

    // Fail-closed: run pure seeded-Omega lock verifier before generating manifest constants.
    let output = Command::new(&verifier)
        .arg("verify")
        .arg(&lock_file)
        .arg(&src_om)
        .arg(&omc_bin)
        .arg(&egp3_cert)
        .arg(&lean_src)
        .arg(&ompk_pkg)
        .arg(&unit_bin)
        .arg(&native_c)
        .arg(&unit_obj)
        .output()
        .unwrap_or_else(|e| {
            panic!(
                "FAIL-CLOSED: cannot execute pure-Omega lock verifier `{}`: {e}",
                verifier.display()
            )
        });

    if !output.status.success() {
        let code = output.status.code().unwrap_or(-1);
        let stderr = String::from_utf8_lossy(&output.stderr);
        panic!(
            "FAIL-CLOSED: pure-Omega lock verification refused build (exit {code}): {}",
            stderr.trim()
        );
    }

    let lock_text = fs::read_to_string(&lock_file).expect("read verified OMEGA_TRACE.lock");
    let mut kv = BTreeMap::new();
    for line in lock_text.lines() {
        if let Some((k, v)) = line.split_once('=') {
            kv.insert(k.to_string(), v.to_string());
        }
    }

    let abi_version: u32 = req(&kv, "ABI_VERSION")
        .parse()
        .expect("parse ABI_VERSION as u32");
    let unit_bin_bytes: u64 = req(&kv, "UNIT_BIN_BYTES")
        .parse()
        .expect("parse UNIT_BIN_BYTES as u64");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let gen_path = out_dir.join("trace_manifest_gen.rs");
    let gen_src = format!(
        r#"// Auto-generated by bridge/rust-trace/crate/build.rs from verified OMEGA_TRACE.lock.
pub const VERIFIED_FORMAT: &str = {format:?};
pub const VERIFIED_UNIT_NAME: &str = {unit_name:?};
pub const VERIFIED_ABI_VERSION: u32 = {abi_version};
pub const VERIFIED_PROFILE: &str = {profile:?};
pub const VERIFIED_OMEGA2_IDENT: &str = {omega2_ident:?};
pub const VERIFIED_SOURCE_OM_SHA256: &str = {src_sha:?};
pub const VERIFIED_OMC_SHA256: &str = {omc_sha:?};
pub const VERIFIED_EGP3_SHA256: &str = {egp3_sha:?};
pub const VERIFIED_LEAN_PROOF_SHA256: &str = {lean_sha:?};
pub const VERIFIED_SEMANTIC_ID: &str = {sem_id:?};
pub const VERIFIED_OMPK_SHA256: &str = {ompk_sha:?};
pub const VERIFIED_UNIT_BIN_SHA256: &str = {ubin_sha:?};
pub const VERIFIED_UNIT_BIN_BYTES: u64 = {unit_bin_bytes};
pub const VERIFIED_NATIVE_C_SHA256: &str = {natc_sha:?};
pub const VERIFIED_UNIT_OBJ_SHA256: &str = {uobj_sha:?};
pub const VERIFIED_CHAIN_ROOT_SHA256: &str = {root_sha:?};

pub const DEFAULT_VERIFIER_PATH: &str = {p_ver:?};
pub const DEFAULT_LOCK_PATH: &str = {p_lock:?};
pub const DEFAULT_SRC_OM_PATH: &str = {p_src:?};
pub const DEFAULT_OMC_PATH: &str = {p_omc:?};
pub const DEFAULT_EGP3_PATH: &str = {p_egp3:?};
pub const DEFAULT_LEAN_PATH: &str = {p_lean:?};
pub const DEFAULT_OMPK_PATH: &str = {p_ompk:?};
pub const DEFAULT_UNIT_BIN_PATH: &str = {p_ubin:?};
pub const DEFAULT_NATIVE_C_PATH: &str = {p_natc:?};
pub const DEFAULT_UNIT_OBJ_PATH: &str = {p_uobj:?};
"#,
        format = req(&kv, "FORMAT"),
        unit_name = req(&kv, "UNIT_NAME"),
        abi_version = abi_version,
        profile = req(&kv, "PROFILE"),
        omega2_ident = req(&kv, "OMEGA2_IDENT"),
        src_sha = req(&kv, "SOURCE_OM_SHA256"),
        omc_sha = req(&kv, "OMC_SHA256"),
        egp3_sha = req(&kv, "EGP3_SHA256"),
        lean_sha = req(&kv, "LEAN_PROOF_SHA256"),
        sem_id = req(&kv, "SEMANTIC_ID"),
        ompk_sha = req(&kv, "OMPK_SHA256"),
        ubin_sha = req(&kv, "UNIT_BIN_SHA256"),
        unit_bin_bytes = unit_bin_bytes,
        natc_sha = req(&kv, "NATIVE_C_SHA256"),
        uobj_sha = req(&kv, "UNIT_OBJ_SHA256"),
        root_sha = req(&kv, "CHAIN_ROOT_SHA256"),
        p_ver = verifier.display().to_string(),
        p_lock = lock_file.display().to_string(),
        p_src = src_om.display().to_string(),
        p_omc = omc_bin.display().to_string(),
        p_egp3 = egp3_cert.display().to_string(),
        p_lean = lean_src.display().to_string(),
        p_ompk = ompk_pkg.display().to_string(),
        p_ubin = unit_bin.display().to_string(),
        p_natc = native_c.display().to_string(),
        p_uobj = unit_obj.display().to_string(),
    );
    fs::write(&gen_path, gen_src).expect("write trace_manifest_gen.rs");
}
