# TEST INSTRUMENT ONLY (fixture builder; never on the product path): revocation signers with weak or
# over-ceiling RSA keys (review omega-mv-tlscap-35d44b5a finding 1, revocation path: rev_sig ->
# chain_sig reads the RSA key size). Writes vectors/revweak/*.der with python cryptography (>= 41).
# Fresh random keys each run; private keys are never written; cases.txt does not depend on key bytes.
# Also writes vectors/revweak/cases.txt (driver.om O records, appended to vectors/cases.txt by run.sh):
# a 1024-bit signer is X509_ERR_WEAK_KEY whatever its exponent; a 2048-bit one is accepted, also with
# e = 2^32+1 (revocation signers, like anchors, need >= 2048 bits; no exponent ceiling applies to them).
#   ocsp: an EC P-256 issuer iss, a leaf by it, and per (bits, e) a delegated OCSP responder
#         resp<bits>e<e> (id-kp-OCSPSigning, issued by iss) with that RSA key, signing a "good" response
#         o_resp<bits>e<e>.der that carries the responder certificate
#   crl:  per (bits, e) an RSA issuer crliss<bits>e<e> (keyCertSign, cRLSign), a leaf lcrl<bits>e<e> by
#         it with a CRL distribution point, and a clean CRL c_<bits>e<e>.der signed by that issuer
# Usage: python3 gen_revweak.py
import calendar
import datetime as dt
import math
import os
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.x509 import ocsp
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "revweak")
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    os.remove(os.path.join(OUT, f))
NOW = dt.datetime(2026, 10, 27)
H = dt.timedelta(hours=1)
D = dt.timedelta(days=1)
NB, NA = dt.datetime(2026, 1, 1), dt.datetime(2027, 1, 1)
DP = "http://crl.example.test/weak.crl"
KEYS = [(1024, 4294967297), (1024, 65537), (2048, 65537), (2048, 4294967297)]


def die(msg):
    sys.exit("gen_revweak.py: " + msg)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def rsa_with_e(bits, e):
    """an RSA key of exactly `bits` bits with public exponent e (odd, coprime to lambda)"""
    while True:
        k = rsa.generate_private_key(public_exponent=65537, key_size=bits)
        p, q = k.private_numbers().p, k.private_numbers().q
        lam = (p - 1) * (q - 1) // math.gcd(p - 1, q - 1)
        if math.gcd(e, lam) == 1:
            d = pow(e, -1, lam)
            k = rsa.RSAPrivateNumbers(p, q, d, rsa.rsa_crt_dmp1(d, p), rsa.rsa_crt_dmq1(d, q),
                                      rsa.rsa_crt_iqmp(p, q), rsa.RSAPublicNumbers(e, p * q)).private_key()
            if k.public_key().key_size != bits or k.public_key().public_numbers().e != e:
                die("key %d/%d came out %d bits" % (bits, e, k.public_key().key_size))
            return k


def cert(cn, pub, icn, ik, serial, ca=False, kus=None, eku=None, dp=False, san=False):
    b = (x509.CertificateBuilder().subject_name(name(cn)).issuer_name(name(icn)).public_key(pub)
         .serial_number(serial).not_valid_before(NB).not_valid_after(NA)
         .add_extension(x509.BasicConstraints(ca=ca, path_length=None), critical=True))
    if kus is not None:
        b = b.add_extension(kus, critical=True)
    if eku is not None:
        b = b.add_extension(x509.ExtendedKeyUsage(eku), critical=False)
    if dp:
        b = b.add_extension(x509.CRLDistributionPoints([x509.DistributionPoint(
            [x509.UniformResourceIdentifier(DP)], None, None, None)]), critical=False)
    if san:
        b = b.add_extension(x509.SubjectAlternativeName([x509.DNSName("www.example.test")]), critical=False)
    return b.sign(ik, hashes.SHA256())


def ku(cert_sign=False, crl_sign=False, ds=True):
    return x509.KeyUsage(ds, False, False, False, False, cert_sign, crl_sign, False, False)


def save(fn, data):
    with open(os.path.join(OUT, fn), "wb") as f:
        f.write(data)


def der(c):
    return c.public_bytes(serialization.Encoding.DER)


ki = ec.generate_private_key(ec.SECP256R1())
iss = cert("RW Issuer", ki.public_key(), "RW Issuer", ki, 1, ca=True, kus=ku(True, True, True))
save("iss.der", der(iss))
kl = ec.generate_private_key(ec.SECP256R1())
leaf = cert("www.example.test", kl.public_key(), "RW Issuer", ki, 0x7001, kus=ku(),
            eku=[ExtendedKeyUsageOID.SERVER_AUTH], san=True)
save("leaf.der", der(leaf))
NOWU = calendar.timegm(NOW.timetuple())
lines = ["# generated by ../../gen_revweak.py, do not edit; NOW = %d = 2026-10-27T00:00:00Z" % NOWU]
for bits, e in KEYS:
    tag = "%de%d" % (bits, e)
    # OCSP: delegated responder with the RSA key, issued by the EC issuer
    rk = rsa_with_e(bits, e)
    resp = cert("RW OCSP Responder " + tag, rk.public_key(), "RW Issuer", ki, 0x7100 + bits,
                kus=ku(), eku=[ExtendedKeyUsageOID.OCSP_SIGNING])
    save("resp%s.der" % tag, der(resp))
    r = (ocsp.OCSPResponseBuilder().add_response(
        cert=leaf, issuer=iss, algorithm=hashes.SHA1(), cert_status=ocsp.OCSPCertStatus.GOOD,
        this_update=NOW - H, next_update=NOW + 3 * D, revocation_time=None, revocation_reason=None)
        .responder_id(ocsp.OCSPResponderEncoding.NAME, resp).certificates([resp]).sign(rk, hashes.SHA256()))
    if ocsp.load_der_ocsp_response(r.public_bytes(serialization.Encoding.DER)).certificates[0] != resp:
        die("response %s does not carry its responder" % tag)
    save("o_resp%s.der" % tag, r.public_bytes(serialization.Encoding.DER))
    # CRL: an RSA issuer with the key signs the leaf and a clean CRL
    ck = rsa_with_e(bits, e)
    icn = "RW CRL Issuer " + tag
    ci = cert(icn, ck.public_key(), icn, ck, 0x7200 + bits, ca=True, kus=ku(True, True, True))
    save("crliss%s.der" % tag, der(ci))
    lc = cert("www.example.test", kl.public_key(), icn, ck, 0x7300 + bits, kus=ku(),
              eku=[ExtendedKeyUsageOID.SERVER_AUTH], dp=True, san=True)
    lc.verify_directly_issued_by(ci)
    save("lcrl%s.der" % tag, der(lc))
    c = (x509.CertificateRevocationListBuilder().issuer_name(name(icn)).last_update(NOW - H)
         .next_update(NOW + 7 * D).add_extension(x509.CRLNumber(7), critical=False)
         .add_revoked_certificate(x509.RevokedCertificateBuilder().serial_number(0x7fff)
                                  .revocation_date(NOW - 2 * D).build())
         .sign(ck, hashes.SHA256()))
    if not c.is_signature_valid(ck.public_key()):
        die("crl %s does not verify" % tag)
    save("c_%s.der" % tag, c.public_bytes(serialization.Encoding.DER))
    want = "X509_ERR_WEAK_KEY" if bits < 2048 else "X509_OK"
    en = "2_32_plus_1" if e == 4294967297 else str(e)
    lines.append("O ocsp_responder_rsa%d_e%s %s %d revweak/leaf.der revweak/iss.der revweak/o_resp%s.der -"
                 % (bits, en, want, NOWU, tag))
    lines.append("O crl_issuer_rsa%d_e%s %s %d revweak/lcrl%s.der revweak/crliss%s.der - revweak/c_%s.der"
                 % (bits, en, want, NOWU, tag, tag, tag))
with open(os.path.join(OUT, "cases.txt"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("revweak fixtures:", len(os.listdir(OUT)))
