#!/usr/bin/env python3
"""fuzz.py SEED OPS OUT.om OUT.want -- gate-pools section 7 (design 7.7): a seeded random sequence of
enlarge/get/put/len/sum operations on two run-time pools (P ulong, U uchar), written as an omc program,
and the output it must print, computed by an independent model (a Python list per pool). The program
prints one line per operation, so the gate compares every step; the last line of OUT.want is the exit
status (`status N`). About one seed in three ends with an index at the length (trap 3, exit 103).
Deterministic: the same SEED and OPS give the same bytes (random.Random(SEED), no other input)."""
import random
import sys

M = 1 << 64
PNUM = """fn pnum v ulong to void
put ob 23 10
i = ulong 23
x = v
go = true
while go bound 21
i = sub i 1
put ob i uchar add rem x 10 48
x = div x 10
go = ne x 0
end
k = write 1 ob i sub 24 i
end
fn plong v long to void
if lt v 0
put ob 0 uchar 45
k = write 1 ob 0 1
pnum ulong neg v
else
pnum ulong v
end
end
fn psum a ulong b ulong to ulong
s = ulong 0
i = a
while lt i b bound 2000000
s = add s get P i
i = add i 1
end
ret s
end
fn usum a ulong b ulong to ulong
s = ulong 0
i = a
while lt i b bound 2000000
s = add s ulong get U i
i = add i 1
end
ret s
end
"""


def gen(seed, ops):
    rnd = random.Random(seed)
    model = {"P": [], "U": []}
    mask = {"P": M - 1, "U": 255}
    esz = {"P": 8, "U": 1}
    src = ["note gate-pools 7: fuzz seed %d, %d operations (generated by seed/omc/tests/pools/fuzz.py)" % (seed, ops),
           "global P ulong *", "global U uchar *", "global ob uchar 24", PNUM.rstrip("\n"), "fn main to int"]
    out = []
    for _ in range(ops):
        name = rnd.choice("PU")
        L = model[name]
        n = len(L)
        k = rnd.random()
        if k < 0.18 or n == 0:
            c = rnd.random()
            if c < 0.2:
                m = rnd.randint(0, n)                       # at or below the length: nothing changes
            elif c < 0.45:
                m = n + rnd.randint(1, 16)                  # a few elements: usually within the page
            elif c < 0.6:
                page = 4096 // esz[name]                    # exactly to, or one past, a page boundary
                m = ((n // page) + rnd.randint(1, 3)) * page + rnd.choice((0, 1))
            elif c < 0.9:
                m = n + rnd.randint(17, 5000)
            else:
                m = n + rnd.randint(5000, 200000)           # a big jump: mremap
            src += ["r = enlarge %s ulong %d" % (name, m), "plong r", "pnum len %s" % name]
            if m > n:
                L.extend([0] * (m - n))
            out += [0, len(L)]
        elif k < 0.40:
            i = rnd.randrange(n)
            if rnd.random() < 0.5:
                src.append("pnum ulong get %s %d" % (name, i))
            else:
                src += ["j = ulong %d" % i, "pnum ulong get %s j" % name]
            out.append(L[i])
        elif k < 0.80:
            i = rnd.randrange(n)
            v = rnd.getrandbits(64) & mask[name]
            if rnd.random() < 0.3:
                v = rnd.choice((0, 1, mask[name]))
            if rnd.random() < 0.5:
                src.append("put %s %d %d" % (name, i, v))
            else:
                src += ["j = ulong %d" % i, "put %s j %d" % (name, v)]
            src.append("pnum ulong get %s %d" % (name, i))
            L[i] = v
            out.append(v)
        elif k < 0.90:
            src.append("pnum len %s" % name)
            out.append(n)
        else:
            a = rnd.randrange(n)
            b = min(n, a + rnd.randint(0, 300))
            src.append("pnum %s %d %d" % ("psum" if name == "P" else "usum", a, b))
            out.append(sum(L[a:b]) % M)
    status = 0
    if rnd.random() < 0.34:
        name = rnd.choice("PU")
        src.append("pnum ulong get %s len %s" % (name, name))
        status = 103
    src += ["ret 0", "end"]
    return "\n".join(src) + "\n", "".join("%d\n" % x for x in out) + "status %d\n" % status


def main():
    if len(sys.argv) != 5:
        sys.exit("usage: fuzz.py SEED OPS OUT.om OUT.want")
    s, w = gen(int(sys.argv[1]), int(sys.argv[2]))
    with open(sys.argv[3], "w") as f:
        f.write(s)
    with open(sys.argv[4], "w") as f:
        f.write(w)


if __name__ == "__main__":
    main()
