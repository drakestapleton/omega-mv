# seed/host/container/mkrefusals.py (test instrument, Python): writes seed/host/container/refusals/ (one unit per word
# and refusal) and refusals.cases from the word table below, so the per-word refusal coverage is generated, never
# typed. seed/host/container/check.sh runs it into a scratch directory and requires the committed files to match.
# For each of the 13 container words: target x86linux (25), target a64efi (25), function mode (9); for each word
# with a byte operand, a ulong array (7); for capget and capset, which write A, a view parameter and a text (20).
# usage: python3 mkrefusals.py DIR   (DIR gets refusals/ and refusals.cases)
import os, sys
W = [  # word, statement with A for the byte operand (None: no byte operand)
    ("unshare", "r = unshare int 0", False),
    ("mount", "r = mount A 0 8 int 0", True),
    ("umount", "r = umount A 0 8 int 0", True),
    ("pivroot", "r = pivroot A 0 8", True),
    ("sethost", "r = sethost A 0 8", True),
    ("prctl", "r = prctl 38 1", False),
    ("sigmask", "r = sigmask int 0 A 0 8", True),
    ("sigwait", "r = sigwait A 0 8", True),
    ("capget", "r = capget A 0 32", True),
    ("capset", "r = capset A 0 32", True),
    ("opentree", "r = opentree A 0 8 int 0", True),
    ("mntattr", "r = mntattr int 3 A 0 32", True),
    ("mntmove", "r = mntmove int 3 int 4", False),
]
out = sys.argv[1]
d = os.path.join(out, "refusals")
os.makedirs(d, exist_ok=True)
rows = []
def unit(name, text, code, word):
    # Each generated refusal declares its actual new keyword and executed owner, never a copied file list.
    declaration = "note gate-pools: uses %s on purpose: owner=seed/host/container/check.sh generated refusal qualification\n" % word
    open(os.path.join(d, name + ".om"), "w").write(text + declaration)
    rows.append("%s refuse seed/host/container/refusals/%s.om %d" % (name, name, code))
for w, st, arr in W:
    body = st.replace("A", "a")
    main = "fn main to int\na = new uchar 64 0\n%s\nret 0\nend\n" % body
    unit("x86-" + w, "target x86linux\nnote x86linux has no lowering of %s: error 25 (target is the first line)\n%s" % (w, main), 25, w)
    unit("a64efi-" + w, "target a64efi\nnote a64efi has no Linux beneath it: every host word, %s too, is error 25\n%s" % (w, main), 25, w)
    unit("fnmode-" + w, "note %s is program-only: function mode (no fn main) is error 9\nfn bad to long\na = new uchar 64 0\n%s\nret r\nend\n" % (w, body), 9, w)
    if arr:
        unit("ulong-" + w, "note %s takes a byte (uchar) array: a ulong array is error 7\nfn main to int\na = new ulong 8 0\n%s\nret 0\nend\n" % (w, body), 7, w)
    if w in ("capget", "capset"):
        unit("view-" + w, "om2\nnote %s writes its header (capset too: the kernel stores its version): a view parameter is error 20\nfn f t view uchar * to long\n%s\nret r\nend\nfn main to int\na = new uchar 64 0\nr = f a\nret 0\nend\n" % (w, st.replace("A", "t")), 20, w)
        unit("text-" + w, "note %s writes its header: a text is error 20\ntext a \"%s\"\nfn main to int\n%s\nret 0\nend\n" % (w, "x" * 40, body), 20, w)
hdr = ("# SPDX-License-Identifier: Apache-2.0\n"
       "# seed/host/container/refusals.cases: generated by seed/host/container/mkrefusals.py (do not edit; rerun it).\n"
       "# Per-word refusals of the container words, run by the OM-2 conductor from seed/host/container/check.sh.\n")
open(os.path.join(out, "refusals.cases"), "w").write(hdr + "\n".join(rows) + "\n")
print("refusals %d" % len(rows))
