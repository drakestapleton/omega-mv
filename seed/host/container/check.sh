#!/bin/sh
# SPDX-License-Identifier: Apache-2.0
# seed/host/container/check.sh [OMC]: gate for the container words 207..214 and 202..206.
# 1. container.cases through the OM-2 conductor (unprivileged runs, refusals, the count, framing preflight and capset-view
#    mutants).
# 2. ORACLE check: oracle.py user (Python ctypes, test instrument) still prints user.want.
# 3. Root mode: container.om and oracle.py run the same words as root (sudo -n) inside their own private
#    mount and UTS namespaces; outputs must be byte-identical and both exit 0. The host hostname and the
#    scratch directories must be unchanged afterwards.
# 4. The root-mode omc.om mutants listed in step 4 below (each word's syscall number, the mount flags, the prctl
#    allowlist and ops, the capget size check, the move_mount flags): the root-mode fixture built by each mutant
#    compiler must fail at its named check (exit = check number); the count printed is the list's.
# Without passwordless sudo, steps 3 and 4 are NOT_RUN and the script exits 3.
set -eu
R=$(CDPATH= cd -- "$(dirname "$0")/../../.." && pwd)
cd "$R"
OMC=${1:-seed/out/omc}
C=seed/host/container
B=build/seed/container
mkdir -p "$B"
run=$(mktemp -d "$B/run.XXXXXX")
pin=$(sha256sum "$OMC" | cut -d' ' -f1)
echo "omc $OMC $pin"
"$OMC" < seed/qualification/om2/gate.om > "$B/gate"
chmod +x "$B/gate"
"$B/gate" "$OMC" "$pin" "$C/container.cases" "$run/cases" > "$run/cases.log" || { cat "$run/cases.log"; exit 1; }
grep -Eqx 'OM2GATE PASS cases=([0-9]+) pass=\1 fail=0 invalid=0 not_run=0' "$run/cases.log" || { cat "$run/cases.log"; exit 1; }
echo "PASS container.cases: $(sed -n 's/^OM2GATE PASS cases=\([0-9]*\) .*/\1/p' "$run/cases.log") cases, every one passed (user-mode parity, long paths and a 90008-byte packet reaching the kernel, framing before allocation, refusals, count and capability mutants)"
# per-word refusals (x86linux, a64efi, function mode, ulong array, view and text for the writing words): the units
# and refusals.cases are generated by mkrefusals.py; the committed ones must be what it writes, then all must pass.
python3 "$C/mkrefusals.py" "$run/gen" > /dev/null
diff -r "$run/gen/refusals" "$C/refusals" > /dev/null && cmp -s "$run/gen/refusals.cases" "$C/refusals.cases" || { echo "FAIL refusals: the committed units differ from mkrefusals.py output"; exit 1; }
"$B/gate" "$OMC" "$pin" "$C/refusals.cases" "$run/refusals" > "$run/refusals.log" || { cat "$run/refusals.log"; exit 1; }
grep -Eqx 'OM2GATE PASS cases=([0-9]+) pass=\1 fail=0 invalid=0 not_run=0' "$run/refusals.log" || { cat "$run/refusals.log"; exit 1; }
echo "PASS refusals.cases: $(sed -n 's/^OM2GATE PASS cases=\([0-9]*\) .*/\1/p' "$run/refusals.log") per-word refusals, generated by mkrefusals.py and equal to the committed units"
python3 "$C/oracle.py" user > "$run/oracle.user"
cmp "$run/oracle.user" "$C/user.want"
echo 'PASS ORACLE oracle.py user == user.want'
# Framing must finish before any mapping, even for a large actual supplied slice (preflight.om modes: m, p a large
# trailing slice; c, q a wrong record count in well-framed records; l, r a count that lies about the records
# supplied; every packet is far past the 65536-byte static region, so a decode would need mmap). The real compiler
# must trap 3 with zero traced mmap/mremap/brk calls (any hint) and no mount/pivot_root. The withdrawn decoder measured one mapping before this
# trap; each mutant below restores that order for some modes and must be seen mapping there:
#   no-prepass (the whole framing prepass skipped): every mode;
#   mount-count-prepass / pivroot-count-prepass (only the prepass record-count check removed): c / q.
# Observer control: a valid 90008-byte mount packet (container.om bigpacket) must show its decode mmap.
"$OMC" < "$C/preflight.om" > "$run/preflight"
chmod +x "$run/preflight"
"$OMC" < "$C/container.om" > "$run/observer"
chmod +x "$run/observer"
set +e
strace -f -o "$run/observer.strace" -e trace=mmap,mount "$run/observer" bigpacket > "$run/observer.out" 2> "$run/observer.err"
pr=$?; set -e
maps=$(grep -c 'mmap(NULL' "$run/observer.strace" || true)
[ "$pr" = 0 ] && [ "$maps" -gt 0 ] || { echo "FAIL observer control: bigpacket exit $pr mmap_calls=$maps (the counter must see a decode mapping)"; exit 1; }
echo "PASS observer control: valid large mount packet exit 0 mmap_calls=$maps"
mutarm() { # ARM FROM TO
  python3 "$C/subst.py" "$2" "$3" seed/omc/omc.om "$run/$1.om"
  "$OMC" < "$run/$1.om" > "$run/$1.omc"
  chmod +x "$run/$1.omc"
  "$run/$1.omc" < "$C/preflight.om" > "$run/$1"
  chmod +x "$run/$1"
}
mutarm preflight-mut seed/host/execfds/mutants/no-prepass.from seed/host/execfds/mutants/no-prepass.to
mutarm preflight-mcount "$C/mutants/mount-count-prepass.from" "$C/mutants/mount-count-prepass.to"
mutarm preflight-pcount "$C/mutants/pivroot-count-prepass.from" "$C/mutants/pivroot-count-prepass.to"
for mode in m p c q l r; do
  arms="preflight preflight-mut"
  [ "$mode" = c ] && arms="$arms preflight-mcount"
  [ "$mode" = q ] && arms="$arms preflight-pcount"
  for arm in $arms; do
    set +e
    strace -f -o "$run/$arm-$mode.strace" -e trace=mmap,mremap,brk,mount,pivot_root "$run/$arm" "$mode" > "$run/$arm-$mode.out" 2> "$run/$arm-$mode.err"
    pr=$?; set -e
    [ "$pr" = 103 ] || { echo "FAIL $arm-$mode exit $pr, wanted framing trap103"; exit 1; }
    # strace starts after its argument execve here; every remaining mmap/mremap/brk request counts at any hint.
    maps=$(grep -Ec '(^|[[:space:]])(mmap|mremap|brk)\(' "$run/$arm-$mode.strace" || true)
    calls=$(grep -Ec '(mount|pivot_root)\(' "$run/$arm-$mode.strace" || true)
    [ "$calls" = 0 ] || { echo "FAIL malformed packet reached kernel operation $arm-$mode"; exit 1; }
    if [ "$arm" = preflight ]; then
      [ "$maps" = 0 ] || { echo "FAIL malformed packet requested decode memory $mode: memory_calls=$maps"; exit 1; }
    else
      [ "$maps" -gt 0 ] || { echo "FAIL mutant $arm not observed allocating before the trap in mode $mode"; exit 1; }
    fi
    echo "PASS $arm-$mode framing trap103 memory_calls=$maps requested_calls=$calls"
  done
done
# The trusted execfds gate checks valid decode memory against its packet-derived budget;
# SECURITY-673 keeps the original hostile-ingress admission limits and mutants unchanged.
# Fail-closed oracle: the recorder (OBOX_ORACLE_FAIL=<step>, no real system calls, the fork test and /proc reads
# simulated) must stop right after each failed setup step with exit 2 and an ABORT line, and with nothing failed it
# must follow the real path to its end. The expected call lists are the dependency order of root mode.
inj() { # STEP EXIT CALLS
    set +e
    OBOX_ORACLE_FAIL=$1 python3 "$C/oracle.py" root /nonexistent > "$run/inj-$1.out" 2> "$run/inj-$1.err"; r=$?
    set -e
    if [ "$r" = "$2" ] && grep -qx "CALLS $3" "$run/inj-$1.err"; then
        if [ "$2" = 2 ] && ! grep -qx "ABORT $1" "$run/inj-$1.out"; then echo "FAIL recorder $1: no ABORT line"; exit 1; fi
        echo "PASS recorder $1: exit $r, calls $3"
    else
        echo "FAIL recorder $1: exit $r"; cat "$run/inj-$1.out" "$run/inj-$1.err"; exit 1
    fi
}
inj unshare 2 'unshare'
inj private 2 'unshare,sethost,capget,get-nnp,private'
inj tmpfs 2 'unshare,sethost,capget,get-nnp,private,tmpfs'
inj mount-bind 2 'unshare,sethost,capget,get-nnp,private,tmpfs,makedir-new,mount-bind'
inj none 0 'unshare,sethost,capget,get-nnp,private,tmpfs,makedir-new,mount-bind,opentree,mntattr-ro,makedir-tgt,tgt-open,mntmove,write-new,prctl-subreaper,fork-pdeathsig,prctl-nonewprivs,sigmask-block-usr1,kill-self,makedir-old,chdir-new,pivroot,stat-old-dir,umount-detach,capset-4fb,capget-after'
if ! sudo -n true 2>/dev/null; then
    echo 'NOT_RUN root mode and syscall mutants: no passwordless sudo'
    exit 3
fi
"$OMC" < "$C/container.om" > "$run/fixture"
chmod +x "$run/fixture"
h0=$(hostname)
d1=$(mktemp -d /tmp/obox-words.XXXXXX)
d2=$(mktemp -d /tmp/obox-words.XXXXXX)
set +e
sudo -n "$run/fixture" root "$d1" > "$run/fixture.root"; fr=$?
sudo -n python3 "$C/oracle.py" root "$d2" > "$run/oracle.root"; orr=$?
sed "s#$d2#$d1#g" "$run/oracle.root" | cmp - "$run/fixture.root"; same=$?
set -e
# host state first, whatever the outputs say
[ "$(hostname)" = "$h0" ] || { echo "FAIL host hostname changed"; exit 1; }
[ -z "$(ls -A "$d1")$(ls -A "$d2")" ] || { echo "FAIL scratch directory changed on the host"; exit 1; }
rmdir "$d1" "$d2"
[ $fr = 0 ] && [ $orr = 0 ] && [ $same = 0 ] || { echo "FAIL root mode: fixture exit $fr, oracle exit $orr, outputs differ=$same"; exit 1; }
echo "PASS root mode: $(wc -l < "$run/fixture.root") results byte-identical with oracle.py, host hostname and scratch unchanged"
# subst.py controls (review omega-mv-d703365f finding 13): a site absent or present twice is refused (exit 2, no
# output written) with and without PYTHONOPTIMIZE; one site succeeds.
printf 'x\nsite\ny\n' > "$run/s1"; printf 'site\nsite\n' > "$run/s2"; printf 'none\n' > "$run/s0"
printf 'site\n' > "$run/sf"; printf 'mut\n' > "$run/st"
for o in "" 1; do
    for k in 0 2; do
        rm -f "$run/sout"
        set +e; PYTHONOPTIMIZE=$o python3 "$C/subst.py" "$run/sf" "$run/st" "$run/s$k" "$run/sout" 2> /dev/null; r=$?; set -e
        [ $r = 2 ] && [ ! -e "$run/sout" ] || { echo "FAIL subst.py accepted $k sites (PYTHONOPTIMIZE=$o): exit $r"; exit 1; }
    done
    rm -f "$run/sout"
    PYTHONOPTIMIZE=$o python3 "$C/subst.py" "$run/sf" "$run/st" "$run/s1" "$run/sout"
    [ "$(cat "$run/sout")" = "$(printf 'x\nmut\ny')" ] || { echo "FAIL subst.py one-site control (PYTHONOPTIMIZE=$o)"; exit 1; }
done
echo "PASS subst.py: 0 and 2 sites refused with nothing written, 1 site substituted, with and without PYTHONOPTIMIZE"
n=0
for m in unshare-sysno:1 mount-sysno:10 mount-flags:10 umount-sysno:35 pivroot-sysno:32 sethost-sysno:20 \
         prctl-allow:40 prctl-sysno:83 sigmask-sysno:50 sigwait-sysno:54 caps-sysno:81 caps-n:81 \
         opentree-sysno:71 mntattr-sysno:72 mntmove-sysno:75 mntmove-flags:75 prctl-23:83 prctl-39:89; do
    name=${m%:*}; want=${m#*:}
    python3 "$C/subst.py" "$C/mutants/$name.from" "$C/mutants/$name.to" seed/omc/omc.om "$run/$name.om"
    "$OMC" < "$run/$name.om" > "$run/$name.omc"
    chmod +x "$run/$name.omc"
    "$run/$name.omc" < "$C/container.om" > "$run/$name.fixture"
    chmod +x "$run/$name.fixture"
    d=$(mktemp -d /tmp/obox-words.XXXXXX)
    set +e
    sudo -n "$run/$name.fixture" root "$d" > "$run/$name.out"
    got=$?
    set -e
    rmdir "$d"
    if [ "$got" = "$want" ]; then
        echo "PASS mutant $name killed (exit $got)"
        n=$((n + 1))
    else
        echo "FAIL mutant $name exit $got, wanted $want"
        exit 1
    fi
done
[ "$(hostname)" = "$h0" ] || { echo "FAIL host hostname changed"; exit 1; }
echo "PASS container words: $n root-mode mutants killed, every one in the list above"
