#!/usr/bin/env python3
"""repin3.py: move the in-repo current-compiler pin to the committed seed/out/omc, over the files the
inline-arena repin d6840959 moved (seed/out/omc.sha256 and seed/omc/size-history.tsv are the landing's).
Run from the repo root of a landing branch.

The pin being replaced (OLD, OLD_SRC) is read from om/units.sh OMC_PIN and native/prefetch/compiler.sha256.
The narrative of the current pin is read from neuralese/README.md ("Current pin after X, branch `B` on
Radicle main M (DATE): committed ..."):
  - B is this run's branch (a rebuild of the same landing): OLD is replaced in place and M is updated;
  - B is another branch (a new landing over a landed pin): OLD becomes the previous pin ("landed as L",
    L = the commit that set OMC_PIN=OLD in om/units.sh, REPIN_PREV_LANDED overrides) in neuralese,
    AUDIT_SCOPE and native/prefetch/README.md, and this landing becomes current.
This landing: BRANCH = REPIN_BRANCH or the checked-out branch; WHAT and LANDING (subject prefix of the
landing commit) from PROFILES[BRANCH], REPIN_WHAT / REPIN_LANDING override; MAIN = REPIN_MAIN or the first
parent of the landing commit on HEAD's first-parent line; DATE = REPIN_DATE or today (UTC).
src/omega_om_units{.c,.ident,_fs.c} and src/omega_native.h are regenerated by om/units.sh with the bridge
pinned in om/omega-bridge.lock (git archive from ../omega-bridge, REPIN_BRIDGE_REPO overrides, into
build/); only the omc= pins may change, then --check must pass. Every text edit is asserted before any
file is written; build/repin3.last records the pin written.
Exit 0 done; 1 an expected text was not found; 3 a prerequisite is missing; 4 regeneration failed."""
import datetime, hashlib, os, re, subprocess, sys

PROFILES = {
    "amdserve/kfd-word": ("omc KFD words: checked ioctl records, mappings and aligned reservations for Linux AArch64/x86 "
                          "(kfdctl, kfdmap, kfdres; constrained to the reviewed UAPI)", "Add checked KFD ioctl"),
    "omc/inline-edges": ("omc inline-cycle check reads the inline-edge tables only (no trap 3 past the calls' "
                         "room; gate-nocaps drives every table past its first room)", "omc: inline-cycle check"),
    "omc/pools": ("omc run-time pools, landing 1 (global NAME T *, enlarge, len; OMEGESE 9.15)",
                  "omc: run-time pools"),
    "omc/pools-arena": ("omc's arena is a run-time pool that grows under a caller-stated memory ceiling, OMC_MEMORY_MAX "
                        "(om4 learns the pool subset and envcnt/envread; error 14 now means the host or the ceiling "
                        "refused)", "omc: the arena a_ar is a run-time pool"),
}
CLASSIFY = "5dd5bb47"  # native/prefetch/README.md: the compilers since b1d9cff6 emit this classifier
FILES = """native/orig4/orig4.pin native/prefetch/compiler.sha256 om/aarch64/parity/run.sh
om/codec/parity/run.sh om/evidence/parity/run.sh om/gpumath/parity/run.sh om/quantity/README.md
om/receipt/README.md om/receipt/parity/run.sh om/sha256/README.md om/units.sh seed/equiv/gate-irequiv.sh
seed/json/tests/gate-json.sh seed/nki/gate-irnki.sh seed/semhash/README.md
seed/semhash/check.sh seed/spirv/gate-irspirv.sh seed/spirv/gate-vkspirv.sh
seed/stablehlo/gate-irstablehlo.sh seed/tensix/gate-tensix.sh seed/wasm/gate-irwasm.sh""".split()
SHORT = ["om/gpumath/README.md", "om/codec/README.md"]
NL, AU, PF = "neuralese/README.md", "AUDIT_SCOPE.md", "native/prefetch/README.md"
GEN = ["src/omega_om_units.c", "src/omega_om_units.ident", "src/omega_om_units_fs.c", "src/omega_native.h",
       "src/omega_api_decl.h"]

def sha(p): return hashlib.sha256(open(p, "rb").read()).hexdigest()
def rd(p): return open(p, encoding="utf-8").read()
def wr(p, s): open(p, "w", encoding="utf-8").write(s)
def die(rc, msg): print("repin3: " + msg, file=sys.stderr); sys.exit(rc)
def git(*a): return subprocess.run(["git"] + list(a), capture_output=True, text=True).stdout.strip()
def once(s, a, b, what):
    n = s.count(a)
    if n != 1: die(1, "%s: %d of %r" % (what, n, a))
    return s.replace(a, b)
def once_re(s, pat, rep, what):
    r, n = re.subn(pat, rep, s)
    if n != 1: die(1, "%s: %d of /%s/" % (what, n, pat))
    return r

# ---- this landing
BRANCH = os.environ.get("REPIN_BRANCH") or git("symbolic-ref", "--short", "-q", "HEAD")
prof = PROFILES.get(BRANCH, (None, None))
WHAT = os.environ.get("REPIN_WHAT") or prof[0]
LANDING = os.environ.get("REPIN_LANDING") or prof[1]
if not (BRANCH and WHAT and LANDING):
    die(3, "branch %r has no profile; set REPIN_BRANCH, REPIN_WHAT and REPIN_LANDING" % BRANCH)
MAIN = os.environ.get("REPIN_MAIN", "")
if not MAIN:  # the landing commit's first parent (HEAD may be a repin commit above the landing)
    for l in git("log", "--first-parent", "-50", "--format=%H %s").splitlines():
        if l.split(" ", 1)[1].startswith(LANDING):
            MAIN = git("rev-parse", "--short=8", l.split()[0] + "^"); break
if not re.fullmatch(r"[0-9a-f]{8}", MAIN or ""):
    die(3, "Radicle main unknown: no %r commit on HEAD's first-parent line; set REPIN_MAIN" % LANDING)
DATE = os.environ.get("REPIN_DATE") or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
WHATB = "%s, branch `%s` on Radicle main %s" % (WHAT, BRANCH, MAIN)
NEW, NEW_SRC = sha("seed/out/omc"), sha("seed/omc/omc.om")

# ---- the pin being replaced and its narrative
m = re.search(r"^OMC_PIN=([0-9a-f]{64})$", rd("om/units.sh"), re.M)
if not m: die(1, "om/units.sh: no OMC_PIN")
OLD = m.group(1)
m = re.search(r"^([0-9a-f]{64})  seed/omc/omc\.om$", rd("native/prefetch/compiler.sha256"), re.M)
if not m: die(1, "native/prefetch/compiler.sha256: no seed/omc/omc.om row")
OLD_SRC = m.group(1)
HEAD_RE = re.compile(r"Current pin after (.*?), branch `([^`]+)` on Radicle main ([0-9a-f]{8}) \((\d{4}-\d\d-\d\d)\): "
                     r"committed\n`seed/out/omc` SHA-256\n`([0-9a-f]{64})`, compiler\nsource SHA-256 `([0-9a-f]{64})`\.\n"
                     r"The previous pin, after ", re.S)
hs = HEAD_RE.findall(rd(NL))
if len(hs) != 1: die(1, "%s: %d current-pin headers" % (NL, len(hs)))
CUR_X, CUR_B, CUR_M, CUR_D, cur_pin, cur_src = hs[0]
if (cur_pin, cur_src) != (OLD, OLD_SRC):
    die(1, "%s names %s/%s as current, om/units.sh and compiler.sha256 %s/%s" % (NL, cur_pin[:8], cur_src[:8], OLD[:8], OLD_SRC[:8]))
chain = CUR_B != BRANCH

out = {}
def cur(p): return out.get(p) or rd(p)
if OLD != NEW:
    for p in (NL, AU, PF):  # a new short sha already named there would make the short-form edits ambiguous
        if NEW[:8] in rd(p): die(1, "%s already names %s; refusing an ambiguous repin" % (p, NEW[:8]))
    for p in FILES:
        s = rd(p)
        if OLD not in s: die(1, "%s: no %s" % (p, OLD))
        out[p] = s.replace(OLD, NEW).replace(OLD_SRC, NEW_SRC)
    for p in SHORT:
        out[p] = once(rd(p), "%s…%s" % (OLD[:8], OLD[-4:]), "%s…%s" % (NEW[:8], NEW[-4:]), p)
    # The prefetch README lists the new omc among those emitting CLASSIFY: check it, never assume it.
    c = subprocess.run(["seed/out/omc"], stdin=open("native/prefetch/classify.om", "rb"), capture_output=True)
    csha = hashlib.sha256(c.stdout).hexdigest()
    if c.returncode != 0 or not csha.startswith(CLASSIFY):
        die(1, "classify.om with the new omc: rc %d sha256 %s, not %s; the README claim would be false"
            % (c.returncode, csha, CLASSIFY))
    if chain:
        L = os.environ.get("REPIN_PREV_LANDED") or git("log", "-1", "--format=%h", "--abbrev=8", "-S", "OMC_PIN=" + OLD, "--", "om/units.sh")
        if not re.fullmatch(r"[0-9a-f]{8,}", L): die(3, "no commit set OMC_PIN=%s; set REPIN_PREV_LANDED" % OLD[:8])
        LD = os.environ.get("REPIN_PREV_LANDED_DATE") or git("log", "-1", "--format=%ad", "--date=short", L)
        tag = "branch `%s`, landed as %s, %s" % (CUR_B, L[:8], LD)
        prevx = CUR_X[:-1] + "; " + tag + ")" if CUR_X.endswith(")") else "%s (%s)" % (CUR_X, tag)
        s = rd(NL)
        a = HEAD_RE.search(s).group(0)
        s = once(s, a, "Current pin after %s (%s): committed\n`seed/out/omc` SHA-256\n`%s`, compiler\n"
                 "source SHA-256 `%s`.\nThe previous pin, after %s, was\n`%s` (source\n`%s`); before that, after "
                 % (WHATB, DATE, NEW, NEW_SRC, prevx, OLD, OLD_SRC), NL)
        for a in ("    %s \\\n" % OLD, "build/nl4-gate seed/out/omc %s " % OLD, "the committed compiler is `%s...`;" % OLD[:8]):
            s = once(s, a, a.replace(OLD, NEW).replace(OLD[:8] + "...", NEW[:8] + "..."), NL)
        out[NL] = s
        s = rd(AU)
        k = "   `%s`,\n   from `seed/omc/omc.om` `%s`; " % (OLD, OLD_SRC)
        if s.count(k) != 1: die(1, "%s: current pin block not found" % AU)
        i = s.index(k); j = s.index("). The earlier audit pins\n", i)
        oldwhat = s[i:j].split("; ", 1)[1]
        out[AU] = s[:i] + "   `%s`,\n   from `seed/omc/omc.om` `%s`; %s). The earlier audit pins\n   `%s` (%s),\n" % (
            NEW, NEW_SRC, WHATB, OLD, oldwhat.replace("\n", " ")) + s[j + len("). The earlier audit pins\n"):]
        s = rd(PF)
        P, N = OLD[:8], NEW[:8]
        s = once(s, "`%s`, built from\n`seed/omc/omc.om` `%s`" % (OLD, OLD_SRC),
                 "`%s`, built from\n`seed/omc/omc.om` `%s`" % (NEW, NEW_SRC), PF)
        s = once(s, "then %s) and" % P, "then %s, then %s) and" % (P, N), PF)
        s = once_re(s, r" and at %s on ([^\s)]+)\)" % P, r", at %s on \1 and at %s on %s)" % (P, N, BRANCH), PF)
        s = once(s, " and %s emit %s" % (P, CLASSIFY), ", %s and %s emit %s" % (P, N, CLASSIFY), PF)
        out[PF] = s
    else:
        for p in (NL, AU, PF):
            s = rd(p)
            if OLD not in s: die(1, "%s: no %s" % (p, OLD))
            out[p] = s.replace(OLD, NEW).replace(OLD_SRC, NEW_SRC).replace(OLD[:8], NEW[:8])
    for p, s in out.items(): wr(p, s)
    print("repinned text %s -> %s %s (%d files; %s)" % (OLD[:8], NEW, NEW_SRC, len(out),
          "%s now previous" % CUR_B if chain else "rebuild of %s" % BRANCH))
else:
    print("text already at", NEW)

# ---- the current narrative names this landing's Radicle main (the landing may have been rebased)
mainre = re.compile(r"branch `%s` on Radicle main [0-9a-f]{8}" % re.escape(BRANCH))
for p in (NL, AU):
    s = rd(p)
    if len(mainre.findall(s)) != 1: die(1, "%s: %d of /%s/" % (p, len(mainre.findall(s)), mainre.pattern))
    t = mainre.sub("branch `%s` on Radicle main %s" % (BRANCH, MAIN), s)
    if t != s: wr(p, t); print("%s: Radicle main -> %s" % (p, MAIN))

# ---- regenerate the C bindings with the pinned bridge; only the omc= pins may change
lock = [l.strip() for l in rd("om/omega-bridge.lock").splitlines() if l.strip() and not l.startswith("#")][0]
native_pin = re.search(r"^NATIVE_PIN=([0-9a-f]{64})$", rd("om/units.sh"), re.M).group(1)
repo = os.environ.get("REPIN_BRIDGE_REPO", os.path.join("..", "omega-bridge"))
bridge = os.path.abspath(os.path.join("build", "bridge-" + lock[:12]))
if not (os.path.exists(bridge + "/src/native.om") and sha(bridge + "/src/native.om") == native_pin):
    os.makedirs(bridge, exist_ok=True)
    a = subprocess.run(["git", "-C", repo, "archive", lock], capture_output=True)
    if a.returncode != 0: die(3, "git archive %s in %s: %s" % (lock, repo, a.stderr.decode().strip()))
    subprocess.run(["tar", "-x", "-C", bridge], input=a.stdout, check=True)
    if sha(bridge + "/src/native.om") != native_pin: die(3, "bridge %s native.om is not %s" % (lock, native_pin))
env = dict(os.environ, OMEGA_OMC=os.path.abspath("seed/out/omc"), OMEGA_BRIDGE=bridge)
before = {p: rd(p) for p in GEN}
r = subprocess.run(["sh", "om/units.sh"], env=env, stdout=subprocess.DEVNULL)
if r.returncode != 0: die(4, "om/units.sh exit %d" % r.returncode)
pin = re.compile(r"omc=[0-9a-f]{64}")
diff = [p for p in GEN if rd(p) != pin.sub("omc=" + NEW, before[p])]
if diff: die(4, "regeneration changed more than the omc pin in: " + " ".join(diff))
r = subprocess.run(["sh", "om/units.sh", "--check"], env=env)
if r.returncode != 0: die(4, "om/units.sh --check exit %d" % r.returncode)
os.makedirs("build", exist_ok=True)
wr("build/repin3.last", "%s %s\n" % (NEW, NEW_SRC))
print("repin3 done: %s omc %s source %s main %s bridge %s" % (BRANCH, NEW, NEW_SRC, MAIN, lock[:8]))
