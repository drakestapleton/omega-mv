#!/usr/bin/env python3
"""Generate RESULTS.md for the dsv41 Arboris prefetch A/B from the stored run files.
usage: results.py EVIDENCE_DIR > RESULTS.md
Every figure is read from a stored file (measured) or computed here from such figures (calculated); the
output says which. Exits 1, after printing, if any run check fails."""
import glob, hashlib, json, os, re, statistics, struct, sys

root = sys.argv[1]
failed = []


def rd(*p):
    return open(os.path.join(root, *p)).read().strip()


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def secs(ns):
    return "%.1f" % (ns / 1e9)


def n(v):
    return "{:,}".format(v)


def check(label, ok):
    if not ok:
        failed.append(label)
    return "PASS" if ok else "FAIL"


def load_run(series, rid):
    r = os.path.join(root, series, "runs", rid)
    g = lambda f: open(os.path.join(r, f)).read().strip()
    stats = g("stats")
    m = re.search(r"STATS hits=(\d+) misses=(\d+) nvme_ns=(\d+) gpu_ns=(\d+) engram_ns=(\d+) trace_sha256=([0-9a-f]{64})", stats)
    a = re.search(r"ARBORIS pf_dispatched=(\d+) pf_hits=(\d+) pf_enabled=(\d)", stats)
    pipe = re.search(r"ARBORIS-PF waited=(\d+) wait_ns=(\d+) dropped_unused=(\d+) failed=(\d+) no_idle_worker=(\d+)", stats)
    look = [(int(x), int(y), int(z)) for x, y, z in re.findall(r"ARBORIS-LOOKAHEAD depth=(\d+) right=(\d+) of=(\d+)", stats)]
    rec = glob.glob(os.path.join(root, series, "receipts", "*-dsv41-pf-%s.json" % rid))
    receipt = json.load(open(rec[0])) if len(rec) == 1 else {}
    routing = open(os.path.join(r, "routing.bin"), "rb").read()
    pairs = set()
    for i in range(len(routing) // 60):
        layer = struct.unpack_from("<I", routing, i * 60 + 8)[0]
        for e in struct.unpack_from("<6I", routing, i * 60 + 12):
            pairs.add((layer, e))
    return {
        "run": rid, "arm": int(g("arm")), "rc": int(g("rc")), "wall_ns": int(g("wall_ns")),
        "cache": g("cache-before").split(),
        "preflight": g("preflight") if os.path.exists(os.path.join(r, "preflight")) else None,
        "binary": g("binary.sha256").split()[0],
        "hits": int(m[1]), "misses": int(m[2]), "nvme_ns": int(m[3]), "gpu_ns": int(m[4]),
        "trace_sha256": m[6], "dispatched": int(a[1]), "used": int(a[2]), "enabled": int(a[3]),
        "tokens": g("tokens").split(), "routing_sha256": hashlib.sha256(routing).hexdigest(),
        "records": len(routing) // 60, "pairs": len(pairs), "receipt": receipt,
        "pipe": [int(x) for x in pipe.groups()] if pipe else None, "look": look,
        "workload": g("workload") if os.path.exists(os.path.join(r, "workload")) else "",
    }


def qualification(series):
    text = rd(series, "qualification.log")
    head = re.search(r"^head ([0-9a-f]{40})$", text, re.M)
    dec = re.search(r"^([0-9a-f]{64})  dsv41-decode$", text, re.M)
    omc = re.search(r"^omc ([0-9a-f]{64})$", text, re.M)
    return {"head": head[1], "decoder": dec[1], "omc": omc[1], "passed": text.splitlines()[-1] == "PREFETCH-MUTANTS PASS",
            "log_sha256": sha(os.path.join(root, series, "qualification.log")),
            "mutants": len(re.findall(r"^PASS mutant ", text, re.M))}


out = []
p = out.append
p("# Results: dsv41-decode Arboris prefetch off versus on (generated)")
p("")
p("Generated by `tools/results.py` from the files in this folder. Do not edit by hand; `tools/verify.sh` regenerates it and fails on any difference.")
p("**Measured** values are read from run files written on the Spark. **Calculated** values are computed here from measured ones.")

for series in sorted(d for d in os.listdir(root) if d.startswith("series-")):
    q = qualification(series)
    runs = [load_run(series, rid) for rid in sorted(os.listdir(os.path.join(root, series, "runs")))]
    p("")
    p("## Series %s" % series.split("-", 1)[1].upper())
    p("")
    p("- Decoder binary sha256 (measured, each run): `%s`" % ", ".join(sorted({r["binary"] for r in runs})))
    p("- Qualification log `%s/qualification.log` (sha256 `%s`): head `%s`, compiler `%s`, built decoder `%s`, %d mutants rejected, last line `%s`."
      % (series, q["log_sha256"], q["head"], q["omc"], q["decoder"], q["mutants"], "PREFETCH-MUTANTS PASS" if q["passed"] else "not PASS"))
    p("- Check, qualification passed: %s" % check(series + " qualification passed", q["passed"]))
    p("- Check, every run used the qualified decoder: %s" % check(series + " binary matches qualification", all(r["binary"] == q["decoder"] for r in runs)))
    heads = sorted({str(r["receipt"].get("git_head")) for r in runs})
    p("- Receipt `git_head` values (measured): %s" % ", ".join("`%s`" % h for h in heads))
    groups = {}
    for r in runs:
        groups.setdefault((-len(r["tokens"]), r["workload"]), []).append(r)
    for gk in sorted(groups):
        g = groups[gk]
        ntok = -gk[0]
        tag = "%s %d tokens %s" % (series, ntok, gk[1])
        p("")
        p("### %d generated tokens%s" % (ntok, (", workload `%s`" % gk[1]) if gk[1] else ""))
        p("")
        p("Measured, one row per run, in run-name order:")
        p("")
        p("| Run | Prefetch | Window | Wall s | Expert load s | GPU s | Lookups | Misses | Dispatched | Used | Load avg at start | New NVRM lines |")
        p("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for r in g:
            rc = r["receipt"]
            p("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                r["run"], "on" if r["arm"] else "off", rc.get("window_id", "?"), secs(r["wall_ns"]), secs(r["nvme_ns"]),
                secs(r["gpu_ns"]), n(r["hits"] + r["misses"]), n(r["misses"]), n(r["dispatched"]), n(r["used"]),
                rc.get("load1_start", "?"), rc.get("nvrm_errors_delta", "?")))
        off = [r for r in g if r["arm"] == 0]
        on = [r for r in g if r["arm"] == 1]
        p("")
        p("| Calculated from the rows above | Prefetch off | Prefetch on |")
        p("| --- | --- | --- |")
        p("| Runs | %d | %d |" % (len(off), len(on)))
        for label, key in (("Wall s", "wall_ns"), ("Expert load s", "nvme_ns"), ("GPU s", "gpu_ns")):
            row = []
            for arm in (off, on):
                v = sorted(x[key] for x in arm)
                row.append("median %s (min %s, max %s)" % (secs(statistics.median(v)), secs(v[0]), secs(v[-1])))
            p("| %s | %s | %s |" % (label, row[0], row[1]))
        mo = statistics.median(x["wall_ns"] for x in off)
        mn = statistics.median(x["wall_ns"] for x in on)
        p("")
        p("- Calculated: median wall time on minus off = %s s (%+.1f%%)." % (secs(mn - mo), 100.0 * (mn - mo) / mo))
        p("- Calculated: slowest off run %s s, fastest on run %s s. Every on run slower than every off run: %s."
          % (secs(max(x["wall_ns"] for x in off)), secs(min(x["wall_ns"] for x in on)),
             "yes" if min(x["wall_ns"] for x in on) > max(x["wall_ns"] for x in off) else "no"))
        p("- Measured: on-arm prefetches dispatched %s, used %s per run." % (
            "/".join(sorted({n(x["dispatched"]) for x in on})), "/".join(sorted({n(x["used"]) for x in on}))))
        if sum(x["dispatched"] for x in on):
            p("- Calculated: share of dispatched prefetches used = %.1f%%." % (100.0 * sum(x["used"] for x in on) / sum(x["dispatched"] for x in on)))
        pairs = sorted({x["pairs"] for x in g})
        p("- Measured from the routing records: %s records per run, %s distinct (layer, expert) pairs." % (
            "/".join(sorted({n(x["records"]) for x in g})), "/".join(n(v) for v in pairs)))
        om = sorted({x["misses"] for x in off})
        if len(om) == 1 and len(pairs) == 1:
            p("- Calculated: off-arm misses %s minus distinct pairs %s = %s reloads after eviction (%.1f%% of misses)."
              % (n(om[0]), n(pairs[0]), n(om[0] - pairs[0]), 100.0 * (om[0] - pairs[0]) / om[0]))
        if any(x["pipe"] for x in on):
            p("- Measured, on-arm prefetch pipeline per run (waited for / dropped unused / failed / guesses skipped, no idle worker): %s."
              % "; ".join("%s %s/%s/%s/%s" % (x["run"], n(x["pipe"][0]), n(x["pipe"][2]), n(x["pipe"][3]), n(x["pipe"][4])) for x in on if x["pipe"]))
            p("- Measured, seconds the on arm waited for a prefetch still being read: %s."
              % ", ".join("%s %s" % (x["run"], secs(x["pipe"][1])) for x in on if x["pipe"]))
            for x in on:
                if x["look"]:
                    p("- Measured, look-ahead guesses confirmed by the true router, %s: %s." % (
                        x["run"], "; ".join("%d layers ahead %s of %s (%.1f%%)" % (dp, n(rt), n(of), 100.0 * rt / of) for dp, rt, of in x["look"] if of)))
            om_ = sorted({x["misses"] for x in off}); nm_ = sorted({x["misses"] + x["used"] for x in on})
            p("- Check, on-arm on-demand loads plus prefetched experts used equals off-arm on-demand loads (%s): %s"
              % ("/".join(n(v) for v in nm_), check(tag + " same loads", om_ == nm_)))
        p("- Routing sha256 (measured, `routing.bin`): %s" % ", ".join("`%s`" % h for h in sorted({x["routing_sha256"] for x in g})))
        p("")
        p("| Check | Result |")
        p("| --- | --- |")
        p("| Every run and receipt exited 0 | %s |" % check(tag + " exit", all(x["rc"] == 0 and x["receipt"].get("exit") == 0 for x in g)))
        p("| Every run started with 0 checkpoint pages cached | %s |" % check(tag + " cold", all(x["cache"][0] == "0" and int(x["cache"][1]) > 0 for x in g)))
        p("| `pf_enabled` in the stats line equals the arm | %s |" % check(tag + " arm", all(x["enabled"] == x["arm"] for x in g)))
        p("| `pfcheck` preflight equals the arm | %s |" % check(tag + " preflight", all(x["preflight"] == "ARBORIS pf_enabled=%d" % x["arm"] for x in g)))
        p("| Off arm dispatched and used nothing | %s |" % check(tag + " off", all(x["dispatched"] == 0 and x["used"] == 0 for x in off)))
        p("| Tokens identical across all runs | %s |" % check(tag + " tokens", len({" ".join(x["tokens"]) for x in g}) == 1))
        p("| Routing identical across all runs | %s |" % check(tag + " routing", len({x["routing_sha256"] for x in g}) == 1))
        p("| Lookups identical across all runs | %s |" % check(tag + " lookups", len({x["hits"] + x["misses"] for x in g}) == 1))

# Model files
have = dict(reversed(l.split(None, 1)) for l in rd("model.sha256").splitlines())
want = dict(reversed(l.split(None, 1)) for l in rd("model-upstream.sha256").splitlines())
shards = sorted(k for k in want if k.endswith(".safetensors"))
match = sum(1 for k in shards if have.get(k) == want[k])
p("")
p("## Model files")
p("")
p("- Measured: `model.sha256` holds the sha256 of each file in the checkpoint folder, hashed on the Spark after series A.")
p("- `model-upstream.sha256` holds the sha256 the publisher lists for each large file (the `lfs.oid` field of the checkpoint's `files.json`).")
p("- Calculated: %d of %d weight shards match the publisher's sha256. Check: %s" % (match, len(shards), check("model shards", match == len(shards) and len(shards) == 48)))
missing = sorted(k for k in want if k not in have)
p("- Publisher-listed large files not on disk: %s." % (", ".join("`%s`" % k for k in missing) if missing else "none"))

# Replay
if os.path.exists(os.path.join(root, "replay.txt")):
    p("")
    p("## Replay of the routing through `tests/arboris/online_adapt_bench.om` (simulation)")
    p("")
    p("The harness replays the measured routing on the CPU. Its counts are simulated, not decoder measurements.")
    p("")
    text = rd("replay.txt")
    for line in text.splitlines():
        m = re.match(r"budget=(\d+) bucket=\d+ cacheCap=(\d+) input_sha256=([0-9a-f]{64}): (\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+)$", line)
        if not m:
            continue
        budget, cap = int(m[1]), int(m[2])
        tok, stat, arb, tot, plain, arbc, pf = (int(m[i]) for i in range(4, 11))
        p("- %d guesses per layer, cache simulation %s: %s of %s routed experts predicted (%.1f%%, calculated); frequency-only baseline %s."
          % (budget, "off" if cap == 0 else "FIFO %d slots per layer" % cap, n(arb), n(tot), 100.0 * arb / tot, n(stat)))
        if cap:
            p("  Simulated cache hits without prefetch %s, with prefetch %s, prefetch hits %s." % (n(plain), n(arbc), n(pf)))
        upper = tok * 39 * budget
        p("  Calculated: at most %s guesses were made (%d positions x 39 layer transitions x %d), so at least %.1f%% of guesses were right."
          % (n(upper), tok, budget, 100.0 * arb / upper))

p("")
p("## Overall")
p("")
p("All checks passed." if not failed else "FAILED checks: " + "; ".join(failed))
print("\n".join(out))
sys.exit(1 if failed else 0)
