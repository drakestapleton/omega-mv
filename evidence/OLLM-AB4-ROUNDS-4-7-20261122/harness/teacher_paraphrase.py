#!/usr/bin/env python3
"""Prep harness (not structural): ask the live q36-35b teacher to reword the INSTRUCTION line of
already-verified OM-2 records. The code is never touched or generated by the teacher: each output
record is `note <reworded instruction>` + the original, mechanically verified function.

usage: teacher_paraphrase.py PORT IN_AUDIT.om OUT.om MAX_RECORDS DEADLINE_SEC SEED [SKIP_FILE]

Mechanical filters on every rewording (rejects are counted, never repaired by hand):
  one line, 12..220 chars, printable ASCII, differs from the original, contains no OM-2 keywords as
  code, and carries exactly the same multiset of integers as the original instruction.
"""
import hashlib, json, random, re, sys, time, urllib.request

port, src, out, max_n, deadline, seed = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
skip = set()
if len(sys.argv) > 7:
    try:
        skip = set(l.strip() for l in open(sys.argv[7]))
    except FileNotFoundError:
        pass

SYS = (
    "You reword one instruction for a small programming task. Reply with exactly one line: the same "
    "instruction said in different words and a different sentence shape. Keep every number as digits, "
    "keep the names a, b, c, n and the words item/items/argument when they appear, and keep the exact "
    "meaning, including every special case. No code, no quotes, no explanation, lower case."
)


def split_by_note(path):
    raw = open(path, "rb").read().replace(b"\x00", b"\n").decode("utf-8", errors="ignore")
    recs, cur = [], []

    def flush():
        if cur and any(l.startswith("fn ") for l in cur):
            s = "\n".join(cur).strip()
            if s.endswith("end"):
                recs.append(s)

    for line in raw.splitlines():
        if line.startswith("note ") and cur and any(l.startswith("fn ") for l in cur):
            flush()
            cur = [line]
        elif line.strip() != "":
            cur.append(line)
    flush()
    return recs


def ints(s):
    return sorted(re.findall(r"\d+", s))


BAD = re.compile(r"(^|\s)(fn |ret |end$|om2|```)")


def ok(orig, para):
    if "\n" in para or not (12 <= len(para) <= 220):
        return "shape"
    if any(ord(c) < 32 or ord(c) > 126 for c in para):
        return "ascii"
    if para == orig:
        return "same"
    if BAD.search(para):
        return "code"
    if ints(orig) != ints(para):
        return "numbers"
    return ""


recs = [r for r in split_by_note(src) if r.splitlines()[0].startswith("note ")]
# one instruction line only, skip plan/repair views and anything already reworded
recs = [r for r in recs if not r.startswith("note ARCH_PLAN") and not r.startswith("note repair") and r.splitlines()[1].startswith("fn ") and hashlib.sha1(r.encode()).hexdigest() not in skip]
rng = random.Random(seed)
rng.shuffle(recs)
recs = recs[:max_n]
t0 = time.time()
kept, rej, err = [], {}, 0
done_src = []
for i, r in enumerate(recs):
    if time.time() - t0 > deadline:
        break
    lines = r.splitlines()
    orig = lines[0][5:]
    body = json.dumps({
        "model": "qwen3.6-35b-a3b-fp8", "max_tokens": 72, "temperature": 0.7,
        "messages": [{"role": "system", "content": SYS}, {"role": "user", "content": orig}],
    }).encode()
    req = urllib.request.Request(f"http://127.0.0.1:{port}/v1/chat/completions", data=body, headers={"Content-Type": "application/json"})
    try:
        resp = json.loads(urllib.request.urlopen(req, timeout=40).read())
        txt = resp["choices"][0]["message"]["content"].strip()
    except Exception as e:
        err += 1
        if err > 25 and not kept:
            print(f"ABORT too many errors: {e}", flush=True)
            break
        continue
    para = txt.splitlines()[0].strip().strip('"').rstrip(".").lower() if txt else ""
    why = ok(orig, para)
    done_src.append(r)
    if why:
        rej[why] = rej.get(why, 0) + 1
        continue
    kept.append((orig, "note " + para + "\n" + "\n".join(lines[1:]) + "\n"))
    if len(kept) % 100 == 0:
        print(f"PROGRESS asked={i+1} kept={len(kept)} sec={time.time()-t0:.0f}", flush=True)

open(out, "wb").write(b"\x00".join(k[1].encode() for k in kept) + (b"\x00" if kept else b""))
open(out + ".pairs.tsv", "w").write("".join(f"{o}\t{k.splitlines()[0][5:]}\n" for o, k in kept))
open(out + ".asked", "w").write("".join(hashlib.sha1(r.encode()).hexdigest() + "\n" for r in done_src))
print(f"PARAPHRASE_SUMMARY asked={len(done_src)} kept={len(kept)} rejected={json.dumps(rej, sort_keys=True)} http_errors={err} sec={time.time()-t0:.0f}", flush=True)
